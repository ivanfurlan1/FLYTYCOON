/**
 * Determina el perfil de color de fuego del motor del cohete (color, matiz RGB, núcleo y toberas)
 * según el modelo, motores modulares, propulsión warp y reacciones químicas atmosféricas.
 */
function getRocketFlameInfo(s) {
    if (!s && typeof ship !== 'undefined') s = ship;
    if (!s) {
        return {
            flameColor: 'standard',
            rgb: [251, 175, 60],
            coreRGB: [255, 248, 230],
            highlightRGB: [254, 240, 138],
            nozzleOffsets: [{ x: -14.5, y: 0, scale: 1.0 }]
        };
    }

    const isWarp = !!(s.warping && (s.fuel > 0 || s.infiniteFuel));
    const mKey = s.modelKey || 'vesper';
    const sScale = s.scale || 1.0;

    let nozzleOffsets = [{ x: -14.5 * sScale, y: 0, scale: 1.0 }];
    let flameColor = isWarp ? 'warp' : 'standard';

    if (mKey === 'custom' || s.customRocket) {
        if (s.customRocket && s.customRocket.engines && s.customRocket.engines.length > 0) {
            const mapCol = (c) => {
                if (isWarp) return 'warp';
                if (c === 'methalox') return 'methalox';
                if (c === 'ion') return 'ion_blue';
                if (c === 'titan') return 'heavy_inferno';
                if (c === 'aerospike') return 'cyan_plasma';
                if (c === 'hawk') return 'ion_blue';
                return 'standard';
            };
            const activeEngines = s.customRocket.engines.filter(eng => eng.active !== false);
            nozzleOffsets = activeEngines.map(eng => ({
                x: (eng.flightX !== undefined ? eng.flightX : -14.5) * sScale,
                y: (eng.flightY !== undefined ? eng.flightY : 0) * sScale,
                scale: eng.scale || 1.0,
                flameColor: mapCol(eng.flameColor),
                angleOffset: eng.angleOffset || 0,
                gimbalEnabled: eng.gimbalEnabled !== false
            }));
            flameColor = nozzleOffsets.length > 0 ? nozzleOffsets[0].flameColor : (isWarp ? 'warp' : 'standard');
        }
    } else if (mKey === 'starship') {
        nozzleOffsets = [
            { x: -16.0 * sScale, y: 0, scale: 1.35 },
            { x: -15.5 * sScale, y: -6.5 * sScale, scale: 0.95 },
            { x: -15.5 * sScale, y: 6.5 * sScale, scale: 0.95 }
        ];
        flameColor = isWarp ? 'warp' : 'methalox';
    } else if (mKey === 'celestia') {
        nozzleOffsets = [
            { x: -15.0 * sScale, y: -5.5 * sScale, scale: 0.85 },
            { x: -15.0 * sScale, y: 5.5 * sScale, scale: 0.85 }
        ];
        flameColor = isWarp ? 'warp' : 'aerospike';
    } else if (mKey === 'titan') {
        nozzleOffsets = [
            { x: -16.5 * sScale, y: -7.0 * sScale, scale: 1.15 },
            { x: -16.5 * sScale, y: 7.0 * sScale, scale: 1.15 }
        ];
        flameColor = isWarp ? 'warp' : 'heavy_inferno';
    } else if (mKey === 'aerodart') {
        nozzleOffsets = [{ x: -12.0 * sScale, y: 0, scale: 0.75 }];
        flameColor = isWarp ? 'warp' : 'cyan_plasma';
    } else if (mKey === 'hyperion') {
        nozzleOffsets = [{ x: -15.5 * sScale, y: 0, scale: 1.1 }];
        flameColor = isWarp ? 'warp' : 'scramjet_violet';
    } else if (mKey === 'drone') {
        nozzleOffsets = [
            { x: -10.0 * sScale, y: -8.0 * sScale, scale: 0.55 },
            { x: -10.0 * sScale, y: 8.0 * sScale, scale: 0.55 }
        ];
        flameColor = isWarp ? 'warp' : 'ion_blue';
    }

    // Reacción de combustión e ionización química al entrar en la atmósfera del planeta cercano
    const pNear = s.nearestPlanet || (typeof ship !== 'undefined' ? ship.nearestPlanet : null);
    if (!isWarp && pNear && pNear.archetype) {
        const dP = Math.hypot(s.x - pNear.x, s.y - pNear.y);
        const atmoDepth = pNear.atmoRadius - pNear.radius;
        const altP = dP - pNear.radius;
        if (altP < atmoDepth * 1.12) {
            const reaction = pNear.archetype.flameReaction;
            if (reaction === 'volcanic') flameColor = 'heavy_inferno';
            else if (reaction === 'toxic') flameColor = 'cyan_plasma';
            else if (reaction === 'cryogenic') flameColor = 'ion_blue';
            else if (reaction === 'anomaly' || reaction === 'hollow') flameColor = 'scramjet_violet';
            else if (reaction === 'desert') flameColor = 'standard';
        }
    }

    let rgb = [251, 175, 60];
    let coreRGB = [255, 248, 230];
    let highlightRGB = [254, 240, 138];

    if (flameColor === 'warp') {
        rgb = [56, 189, 248];
        coreRGB = [224, 242, 254];
        highlightRGB = [186, 230, 253];
    } else if (flameColor === 'methalox') {
        rgb = [45, 212, 191];
        coreRGB = [240, 253, 250];
        highlightRGB = [153, 246, 228];
    } else if (flameColor === 'heavy_inferno') {
        rgb = [249, 115, 22];
        coreRGB = [255, 241, 242];
        highlightRGB = [254, 215, 170];
    } else if (flameColor === 'cyan_plasma' || flameColor === 'aerospike') {
        rgb = [52, 211, 153];
        coreRGB = [236, 253, 245];
        highlightRGB = [167, 243, 208];
    } else if (flameColor === 'scramjet_violet') {
        rgb = [192, 132, 252];
        coreRGB = [255, 255, 255];
        highlightRGB = [233, 213, 255];
    } else if (flameColor === 'ion_blue') {
        rgb = [56, 189, 248];
        coreRGB = [240, 249, 255];
        highlightRGB = [186, 230, 253];
    } else {
        rgb = [251, 175, 60];
        coreRGB = [255, 248, 230];
        highlightRGB = [254, 240, 138];
    }

    return { flameColor, rgb, coreRGB, highlightRGB, nozzleOffsets };
}




