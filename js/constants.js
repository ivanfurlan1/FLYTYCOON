function getRocketModel(id) {
    if (!id || !ROCKET_MODELS[id]) return ROCKET_MODELS.vesper;
    return ROCKET_MODELS[id];
}

function applyRocketModel(s, modelId) {
    if (!s) return;
    let m = (modelId === 'custom' && s.customRocket && s.customRocket.customParts)
        ? s.customRocket
        : getRocketModel(modelId);
    s.modelKey = m.id;
    s.customRocket = (m.id === 'custom' && m.customParts) ? m : null;
    s.mass = m.mass;
    s.inertia = m.inertia;
    s.maxFuel = m.fuelCapacity;
    s.fuelConsumption = m.fuelConsumption;
    s.maxHull = m.maxHull;
    s.passengers = m.passengers;
    s.scale = m.scale;
    s.thrust = m.thrust;
    s.warpThrust = m.warpThrust;
    s.maxSpeed = m.maxSpeed;
    s.warpMaxSpeed = m.warpMaxSpeed;
    s.smokeScale = m.smokeScale;
    s.turnRate = m.turnRate;
    s.specialAbility = m.specialAbility;
    s.contactPoints = m.contactPoints;
    
    // Normalizar o cargar reservas iniciales
    if (s.hull === undefined || s.hull > s.maxHull) s.hull = s.maxHull;
    if (s.fuel === undefined || s.fuel > s.maxFuel) s.fuel = s.maxFuel;
    if (typeof ship !== 'undefined' && s === ship && typeof LightingEngine !== 'undefined' && LightingEngine.syncRocketLightsHudBtn) {
        LightingEngine.syncRocketLightsHudBtn();
    }
    return s;
}

